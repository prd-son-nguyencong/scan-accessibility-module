import { existsSync } from 'node:fs';
import { loadBuiltInRuleRegistry } from '../../src/scanner/access-scan/engine/builtin-registry.js';
import { canonicalizeRuleId } from '../../src/reporter/rule-aliases.js';

const SEEDS = new URL('../../test/fixtures/rule-seeds/', import.meta.url);

/** Registry-derived facts the docs and the doc test both rely on. */
export async function ruleDocFacts() {
  const rules = (await loadBuiltInRuleRegistry()).listRules();
  const active = rules.filter((rule) => rule.status === 'active');
  return { rules, active: active.length, legacy: rules.length - active.length };
}

/** Renders docs/accessscan-rule-coverage.md entirely from the registry. */
export async function renderRuleCoverageDoc() {
  const { rules, active, legacy } = await ruleDocFacts();
  const rows = rules.map((rule) => {
    const profiles = [...new Set(rule.checks.flatMap((check) => check.profiles))].join(', ') || '-';
    const { version, level, criterion } = rule.standard;
    const seeds = existsSync(new URL(`${rule.id}/bad.html`, SEEDS)) ? 'yes' : 'no';
    return `| \`${rule.id}\` | \`${canonicalizeRuleId(rule.id)}\` | ${rule.status} | ${profiles} | ${criterion} (${version} ${level}) | ${rule.publicCategory || rule.category} | ${rule.kind ?? ''} | ${rule.kindRationale ?? ''} | ${seeds} |`;
  });
  return [
    '# accessScan Rule Coverage',
    '',
    '<!-- GENERATED by `npm run docs:rules` from the rule registry. Do not edit by hand. -->',
    '',
    `**Total rule IDs:** ${active} active plus ${legacy} legacy-readable`,
    '',
    '| Rule ID | Canonical ID | Status | Profiles | WCAG SC | Category | Kind | Why this kind | Seeds |',
    '|---|---|---|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}
