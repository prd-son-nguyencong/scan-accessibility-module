import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { getBrowser, closeBrowser, newPage } from '../../src/scanner/browser.js';
import { installRuntimeHooks } from '../../src/scanner/access-scan/runtime/index.js';
import { scanWithAccessScan } from '../../src/scanner/access-scan/index.js';
import { loadBuiltInRuleRegistry } from '../../src/scanner/access-scan/engine/builtin-registry.js';

export const SEED_DIR = new URL('../../test/fixtures/rule-seeds/', import.meta.url);
const KNOWN_GAPS = new URL('KNOWN-GAPS.md', SEED_DIR);
// Seeds are tiny static pages: skip the scroll activation and shorten the DOM-stability wait.
export const FAST = { profile: 'standards', activateContent: false, stabilityQuietMs: 30, stabilityMinObserveMs: 30 };
const WORKERS = 2;

/** All seed files as { ruleId, file, expect: 'bad'|'good' } (bad.html, good.html, bad-<case>.html, good-<case>.html). */
export function listSeeds() {
  return readdirSync(SEED_DIR, { withFileTypes: true }).filter((d) => d.isDirectory()).flatMap((d) =>
    readdirSync(new URL(`${d.name}/`, SEED_DIR))
      .filter((file) => /^(bad|good)(-.+)?\.html$/.test(file))
      .map((file) => ({ ruleId: d.name, file, expect: file.startsWith('bad') ? 'bad' : 'good' })));
}

/** `RuleId/file.html` entries listed as bullets in KNOWN-GAPS.md: failing seeds we recorded instead of adjusting. */
export function knownGaps() {
  if (!existsSync(KNOWN_GAPS)) return new Set();
  return new Set([...readFileSync(KNOWN_GAPS, 'utf8').matchAll(/^- `([A-Za-z0-9]+\/[^`]+\.html)`/gm)].map((m) => m[1]));
}

/** Scans every seed with two reused pages of one shared browser; returns seeds with `flagged` (count of that rule's findings). */
export async function runSeeds(seeds = listSeeds()) {
  const browser = await getBrowser();
  const queue = [...seeds];
  const results = [];
  const worker = async () => {
    const page = await newPage(browser);
    try {
      await installRuntimeHooks(page);
      for (let seed = queue.shift(); seed; seed = queue.shift()) {
        await page.setContent(readFileSync(new URL(`${seed.ruleId}/${seed.file}`, SEED_DIR), 'utf8'));
        const violations = await scanWithAccessScan(page, `fixture://seed/${seed.ruleId}/${seed.file}`, { skipNavigation: true, ...FAST });
        results.push({ ...seed, flagged: violations.filter((v) => v.ruleId === seed.ruleId).length });
      }
    } finally {
      await page.context().close();
    }
  };
  try {
    await Promise.all(Array.from({ length: WORKERS }, worker));
  } finally {
    await closeBrowser();
  }
  return results.sort((a, b) => `${a.ruleId}/${a.file}`.localeCompare(`${b.ruleId}/${b.file}`));
}

export const seedPassed = (r) => (r.expect === 'bad' ? r.flagged > 0 : r.flagged === 0);

export async function deterministicRules() {
  return (await loadBuiltInRuleRegistry()).listRules().filter((r) => r.status === 'active' && r.kind === 'deterministic');
}

// Deterministic rules that cannot be seeded as a static page, with the reason. Empty: every one has seeds.
export const UNSEEDABLE = {};

/** Renders docs/seeds-coverage.md from seed results (deterministic text: no timings). */
export function renderSeedsCoverage(results, rules) {
  const gaps = knownGaps();
  const rows = rules.map((rule) => {
    const own = results.filter((r) => r.ruleId === rule.id);
    const bad = own.filter((r) => r.expect === 'bad');
    const good = own.filter((r) => r.expect === 'good');
    const tp = bad.filter((r) => r.flagged > 0).length;
    const fn = bad.length - tp;
    const fp = good.filter((r) => r.flagged > 0).length;
    return { rule, bad: bad.length, good: good.length, tp, fp, fn, seeded: own.length > 0 };
  });
  const seeded = rows.filter((r) => r.seeded);
  const sum = (key) => seeded.reduce((total, r) => total + r[key], 0);
  const pct = rows.length ? Math.round((seeded.length / rows.length) * 100) : 0;
  const cell = (r, n, total) => (r.seeded ? `${n}/${total}` : '-');
  const lines = [
    '# Seeded-fault coverage',
    '',
    '<!-- GENERATED by `npm run seeds:report` from test/fixtures/rule-seeds. Do not edit by hand. -->',
    '',
    'Every `deterministic` accessScan rule gets a minimal page it must flag (`bad*.html`) and a clean twin it must stay silent on (`good*.html`), authored from the WCAG/ARIA text. TP = bad seeds flagged, FN = bad seeds missed, FP = good seeds flagged. Seeds run through the `standards` profile. Scope is the accessScan registry; axe-layer rules (contrast, heading order, duplicate ids, target size...) are not seeded here.',
    '',
    `**Deterministic rules seeded:** ${seeded.length} of ${rows.length} (${pct}%). **Totals:** TP ${sum('tp')}, FN ${sum('fn')}, FP ${sum('fp')}.`,
    ...(gaps.size ? ['', `**Known failing seeds (see test/fixtures/rule-seeds/KNOWN-GAPS.md):** ${[...gaps].join(', ')}`] : []),
    '',
    '| Rule | Seeds | Bad flagged | Good silent | TP | FP | FN |',
    '|---|---|---|---|---|---|---|',
    ...rows.map((r) => `| \`${r.rule.id}\` | ${r.seeded ? 'yes' : 'no'} | ${cell(r, r.tp, r.bad)} | ${cell(r, r.good - r.fp, r.good)} | ${r.seeded ? r.tp : '-'} | ${r.seeded ? r.fp : '-'} | ${r.seeded ? r.fn : '-'} |`),
  ];
  const unseeded = rows.filter((r) => !r.seeded);
  lines.push('', '## Not seeded', '');
  lines.push(...(unseeded.length
    ? unseeded.map((r) => `- \`${r.rule.id}\`: ${UNSEEDABLE[r.rule.id] ?? 'no seed written yet'}`)
    : ['None: every deterministic rule has seeds.']));
  const ids = new Set(rules.map((r) => r.id));
  const others = [...new Set(results.filter((r) => !ids.has(r.ruleId)).map((r) => r.ruleId))];
  if (others.length) lines.push('', `Heuristic rules also seeded (only where the behaviour is clear; the other heuristic rules have no seeds): ${others.map((id) => `\`${id}\``).join(', ')}.`);
  return `${lines.join('\n')}\n`;
}
