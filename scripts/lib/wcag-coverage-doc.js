import axe from 'axe-core';
import { ruleDocFacts } from './rule-doc.js';
import { DEFAULT_HTML_VALIDATE_RULES, HTML_VALIDATE_WCAG } from '../../src/scanner/html-validate.js';
import { WCAG_CRITERIA, wcagCoverageSentence } from '../../src/utils/wcag-criteria.js';

// The axe tags the scanner runs (src/scanner/axe.js WCAG_TAGS); a tag like wcag1410 names SC 1.4.10.
const AXE_TAGS = ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa'];

/** Rule ids per success criterion: { [sc]: { axe: [], accessScan: [], htmlValidate: [] } }. */
export async function rulesBySuccessCriterion() {
  const map = {};
  const add = (sc, engine, id) => {
    const entry = (map[sc] ??= { axe: [], accessScan: [], htmlValidate: [] });
    if (!entry[engine].includes(id)) entry[engine].push(id);
  };
  for (const rule of axe.getRules(AXE_TAGS)) {
    for (const tag of rule.tags) {
      const m = /^wcag(\d)(\d)(\d+)$/.exec(tag);
      if (m) add(`${m[1]}.${m[2]}.${m[3]}`, 'axe', rule.ruleId);
    }
  }
  for (const rule of (await ruleDocFacts()).rules) if (rule.status === 'active') add(rule.standard.criterion, 'accessScan', rule.id);
  for (const [id, sc] of Object.entries(HTML_VALIDATE_WCAG)) {
    const setting = DEFAULT_HTML_VALIDATE_RULES[id];
    if ((Array.isArray(setting) ? setting[0] : setting) !== 'off') add(sc, 'htmlValidate', `html-validate:${id}`);
  }
  for (const entry of Object.values(map)) for (const list of Object.values(entry)) list.sort();
  return map;
}

const cell = (ids) => (ids?.length ? ids.map((id) => `\`${id}\``).join(', ') : '-');

/** Renders docs/wcag-coverage.md from the criteria data file and the rule registries. */
export async function renderWcagCoverageDoc() {
  const map = await rulesBySuccessCriterion();
  const row = (c) => `| ${c.id} | ${c.level === 'obsolete' ? 'obsolete in 2.2' : c.level} | ${c.title} | ${c.coverage} | ${cell(map[c.id]?.axe)} | ${cell(map[c.id]?.accessScan)} | ${cell(map[c.id]?.htmlValidate)} | ${c.note} |`;
  const table = (rows) => [
    '| SC | Level | Title | Coverage | axe | accessScan | html-validate | Rationale |',
    '|---|---|---|---|---|---|---|---|',
    ...rows.map(row),
  ];
  const aa = WCAG_CRITERIA.filter((c) => c.level === 'A' || c.level === 'AA');
  const other = WCAG_CRITERIA.filter((c) => !aa.includes(c));
  return [
    '# WCAG 2.2 Coverage Matrix',
    '',
    '<!-- GENERATED by `npm run docs:wcag` from src/utils/wcag-criteria.js and the rule registries. Do not edit by hand. -->',
    '',
    wcagCoverageSentence(),
    '',
    `Coverage levels: **full** (automated checks decide the criterion's testable requirement), **partial** (some failures are found, a person must still check), **manual-only** (needs human judgement), **none** (automatable in principle, no rule runs yet). Partial is never counted as full.`,
    `Axe rules come from axe-core ${axe.version} (tags run by the scanner), accessScan rules from the registry, html-validate rules from the default preset (rules set to off are not listed). Keyboard, focus-trap, aria-live and screen-reader probes are not in a registry and are not counted. Rules without a WCAG criterion (best practice) are not listed.`,
    '',
    '## Level A and AA criteria',
    '',
    ...table(aa),
    '',
    '## Other criteria (AAA the project touches, obsolete 4.1.1)',
    '',
    ...table(other),
    '',
  ].join('\n');
}
