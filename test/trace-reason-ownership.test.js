import './helpers/hermetic-env.mjs';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildScanReportV2, validateScanReportV2 } from '../src/reporter/report-v2.js';
import { buildQaModel, renderQaHtml } from '../src/reporter/qa-report.js';
import { buildAxeEvidence } from '../src/scanner/axe.js';

const CTX = { generatedAt: '2026-10-27T00:00:00.000Z', producer: { name: 'ada-scan', version: '1.0.1' }, target: { mode: 'url-only', url: 'https://example.test/' } };
const RUNS = [{ layer: 'axe', engine: { name: 'axe-core', version: '4.12.1' }, status: 'complete' }];
const v = (ruleId, selector, outerHTML, source, count = 1) => ({
  ruleId, nativeRuleId: ruleId, layer: 'axe', impact: 'serious', count, verdict: 'confirmed',
  element: { selector, outerHTML }, source,
});
const build = (violations) => buildScanReportV2([{ page: 'home', url: 'https://example.test/', scannerRuns: RUNS, violations }], CTX);
const byRule = (r) => Object.fromEntries(r.pages[0].findings.map((f) => [f.nativeRuleId, f]));

test('no local source: file null and a traceReason, whichever legacy placeholder the tracer used', () => {
  const r = build([
    v('image-alt', 'img.a', '<img class="a" src="a.png">', { file: 'unknown', line: null, confidence: 'none', method: 'no-source-project' }),
    v('label', 'input.b', '<input class="b">', { file: null, line: null, confidence: 'none', method: 'unresolved' }),
    v('link-name', '[data-react-component="JobList"] a', '<a href="/jobs"></a>', { file: 'unknown', line: null, confidence: 'none', method: 'no-source-project' }),
  ]);
  validateScanReportV2(r);
  const f = byRule(r);
  assert.deepEqual([f['image-alt'].source.file, f['image-alt'].source.traceReason], [null, 'no-source-project']);
  assert.deepEqual([f.label.source.file, f.label.source.traceReason], [null, 'unresolved']);
  assert.equal(f['link-name'].ownership, 'platform');
  assert.equal(f['link-name'].source.traceReason, 'platform-owned');
});

test('a traced source-owned finding gets no traceReason', () => {
  const r = build([v('image-alt', 'img.a', '<img class="a" src="a.png">', { file: 'src/pages/a.liquid', line: 3, confidence: 'medium', method: 'marker' })]);
  assert.equal(byRule(r)['image-alt'].source.traceReason, undefined);
});

test('summary: ownershipCounts sums occurrences, ownershipFindingCounts counts findings', () => {
  const r = build([
    v('image-alt', 'img.a', '<img class="a" src="a.png">', { method: 'unresolved' }),
    v('link-name', '[data-react-component="JobList"] a', '<a href="/jobs"></a>', { method: 'unresolved' }, 5),
    v('button-name', '[data-react-component="JobList"] button', '<button></button>', { method: 'unresolved' }, 2),
  ]);
  assert.deepEqual(r.summary.ownershipCounts, { source: 1, platform: 7, thirdParty: 0 });
  assert.deepEqual(r.summary.ownershipFindingCounts, { source: 1, platform: 2, thirdParty: 0 });
});

test('axe evidence drops the constant tracking query from helpUrl, keeps other URLs', () => {
  const ev = (helpUrl) => buildAxeEvidence({ helpUrl }, {}).helpUrl;
  assert.equal(ev('https://dequeuniversity.com/rules/axe/4.12/button-name?application=playwright'), 'https://dequeuniversity.com/rules/axe/4.12/button-name');
  assert.equal(ev('https://dequeuniversity.com/rules/axe/button-name'), 'https://dequeuniversity.com/rules/axe/button-name');
});

test('QA html: rule headings are h3 under the h2 section, and a footer names the generator and date', () => {
  const html = renderQaHtml(buildQaModel(build([v('image-alt', 'img.a', '<img class="a" src="a.png">', { method: 'unresolved' })])));
  assert.doesNotMatch(html, /<h4/);
  assert.match(html, /<h3 id="rule-image-alt">/);
  assert.match(html, /<footer class="wrap"><p>Generated by ada-scan on 2026-10-27T00:00:00\.000Z\.<\/p><\/footer>/);
});

test('vendor DOM (consent banner SDK) is third-party and never confirmed, even with a measured proof', () => {
  const src = { method: 'unresolved' };
  const r = build([
    { ...v('label', '#chkbox-id', '<input id="chkbox-id">', src), element: { selector: '#chkbox-id', outerHTML: '<input id="chkbox-id">' }, evidence: { proof: { type: 'attribute-value', fact: 'id "chkbox-id"' } },
      origin: { owner: 'third-party', kind: 'vendor-script', label: 'Cookie consent (vendor-script: onetrust)', evidence: ['x'], vendor: 'onetrust' } },
    { ...v('image-alt', 'img.a', '<img class="a" src="a.png">', src), evidence: { proof: { type: 'attribute-value', fact: 'src "a.png"' } } },
  ]);
  const f = r.pages[0].findings.find((x) => x.nativeRuleId === 'label');
  assert.equal(f.origin.owner, 'third-party');
  assert.equal(f.verdict, 'needs-review');
  assert.equal(f.evidence.proof, undefined);
  assert.equal(r.pages[0].findings.find((x) => x.nativeRuleId === 'image-alt').verdict, 'confirmed');
});
